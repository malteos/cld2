#!/usr/bin/env python3
"""Derive CHALIS-oriented knowledge from the vocabularies and UD example texts.

CHALIS (Challenging Language Identification Samples, Tichy & Libovicky 2026) tests
LID on (a) cousin languages and (b) non-standard orthography. This script writes:

1. ``<code>/variants/`` -- orthographic variants of vocabulary and example texts:
   * romanized_en (ru, uk, bg, mk, sr; English-style "translit")
   * romanized_cs (ru; Czech-style orthography)
   * arabic_script (kk; tote jazuw)
   * no_diacritics (cs, sk, vi)
   * homoglyphs (cs, sk, en; Latin letters swapped for Cyrillic/Greek look-alikes)
   * leetspeak, antspeak (en)
2. ``chalis/discriminators/<a>-<b>.tsv`` -- frequent words of language A that are
   rare/absent in B (and vice versa), also for the romanized and diacritic-free forms.

Variant texts are deterministic transformations of authentic text; they model the
CHALIS perturbations but are not the CHALIS data itself.

Usage: .venv/bin/python languages/scripts/build_chalis_variants.py
"""
import json
import os
import random
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from translit import cyr2lat_cs, cyr2lat_en, kk_cyr2arab, strip_diacritics  # noqa: E402

BASE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CHALIS_DIR = os.path.join(BASE, "chalis")
TOP_VOCAB = 3000
N_EXAMPLES = 4

HOMO = {"a": "а", "c": "с", "e": "е", "o": "о", "p": "р", "x": "х", "y": "у", "i": "і",
        "A": "А", "B": "В", "C": "С", "E": "Е", "H": "Н", "K": "К", "M": "М", "O": "О",
        "P": "Р", "T": "Т", "X": "Х", "j": "ј", "s": "ѕ", "v": "ν"}
LEET = {"a": "4", "e": "3", "i": "1", "o": "0", "s": "5", "t": "7", "l": "1", "b": "8", "g": "9"}


def vocab(code):
    return [e["word"] for e in json.load(open(os.path.join(BASE, code, "vocabulary.json"), encoding="utf-8"))]


def examples(code, n=N_EXAMPLES):
    d = os.path.join(BASE, code, "examples")
    files = sorted(f for f in os.listdir(d) if f.startswith("ud_") and f.endswith(".txt"))[:n]
    return [(f, open(os.path.join(d, f), encoding="utf-8").read().strip()) for f in files]


def homoglyph(s, rate=0.5, seed=0):
    rnd = random.Random(seed)
    return "".join(HOMO[c] if c in HOMO and rnd.random() < rate else c for c in s)


def leet(s, rate=0.7, seed=0):
    rnd = random.Random(seed)
    return "".join(LEET[c.lower()] if c.lower() in LEET and rnd.random() < rate else c for c in s)


def antspeak(s):
    return " ".join(" ".join(w) for w in s.split())


def write_variant(code, name, fn, desc):
    out = os.path.join(BASE, code, "variants", name)
    os.makedirs(out, exist_ok=True)
    words = vocab(code)[:TOP_VOCAB]
    with open(os.path.join(out, "vocabulary.tsv"), "w", encoding="utf-8") as f:
        f.write("rank\tstandard\tvariant\n")
        for i, w in enumerate(words, 1):
            f.write(f"{i}\t{w}\t{fn(w)}\n")
    for fname, text in examples(code):
        with open(os.path.join(out, fname), "w", encoding="utf-8") as f:
            f.write(fn(text) + "\n")
    with open(os.path.join(out, "README.md"), "w", encoding="utf-8") as f:
        f.write(f"# {code} -- {name}\n\n{desc}\n\n"
                f"- `vocabulary.tsv`: top {TOP_VOCAB} words, standard form vs. variant form\n"
                f"- `ud_NN.txt`: authentic UD example passages after the transformation "
                f"(see `../../examples/SOURCES.md`)\n\n"
                f"Generated by `languages/scripts/build_chalis_variants.py` (deterministic; synthetic noise "
                f"applied to real text).\n")
    print(f"{code}/variants/{name}")


VARIANTS = [
    ("rus_Cyrl", "romanized_en", lambda s: cyr2lat_en(s, "ru"), "Russian typed in Latin letters with English-style conventions (zh, kh, ts, ch, sh, shch, ya, yu). CHALIS section `cyrillic_to_english`."),
    ("rus_Cyrl", "romanized_cs", cyr2lat_cs, "Russian typed in Latin letters with Czech orthography (ž, ch, c, č, š, šč, ja, ju). CHALIS section `cyrillic_to_czech`."),
    ("bul_Cyrl", "romanized_en", lambda s: cyr2lat_en(s, "bg"), "Bulgarian in Latin letters, English-style (sht for щ, a for ъ). CHALIS `cyrillic_to_english`."),
    ("mkd_Cyrl", "romanized_en", lambda s: cyr2lat_en(s, "mk"), "Macedonian in Latin letters, English-style (gj/kj for ѓ/ќ, dz for ѕ/џ). CHALIS `cyrillic_to_english`."),
    ("srp_Cyrl", "romanized_en", lambda s: cyr2lat_en(s, "sr"), "Serbian Cyrillic typed in plain ASCII Latin (diacritics of Gaj's alphabet dropped: c for č/ć, s for š, z for ž, dj for đ). CHALIS `cyrillic_to_english`."),
    ("ukr_Cyrl", "romanized_en", lambda s: cyr2lat_en(s, "uk"), "Ukrainian in Latin letters, English-style (h for г, y for и, yi for ї). Distractor for the Cyrillic-to-Latin sections (CHALIS ships unlabelled Ukrainian there)."),
    ("kaz_Cyrl", "arabic_script", kk_cyr2arab, "Kazakh in the Arabic-based tote jazuw script (used by Kazakhs in China, Iran, Afghanistan). CHALIS section `arabic`. Simplified rule-based conversion."),
    ("ces_Latn", "no_diacritics", strip_diacritics, "Czech without diacritics (háčky and čárky removed), as typed on phones/SMS. CHALIS section `diacritics`."),
    ("slk_Latn", "no_diacritics", strip_diacritics, "Slovak without diacritics (mäkčene, dĺžne, vokáň removed). CHALIS section `diacritics`."),
    ("vie_Latn", "no_diacritics", strip_diacritics, "Vietnamese without tone marks and vowel diacritics (telex-less ASCII). CHALIS section `diacritics`."),
    ("ces_Latn", "homoglyphs", homoglyph, "Czech with ~50% of eligible Latin letters replaced by Cyrillic/Greek look-alikes. CHALIS section `homoglyphs`."),
    ("slk_Latn", "homoglyphs", homoglyph, "Slovak with Cyrillic/Greek look-alike substitutions. CHALIS section `homoglyphs`."),
    ("eng_Latn", "homoglyphs", homoglyph, "English with Cyrillic/Greek look-alike substitutions. CHALIS section `homoglyphs`."),
    ("eng_Latn", "leetspeak", leet, "English in leetspeak (a->4, e->3, o->0, s->5, t->7, ...). CHALIS section `leetspeak`."),
    ("eng_Latn", "antspeak", antspeak, "English with every letter separated by spaces ('a n t s p e a k'). CHALIS section `antspeak`."),
]

PAIRS = [
    ("ces_Latn", "slk_Latn", None), ("ces_Latn", "slk_Latn", strip_diacritics),
    ("spa_Latn", "cat_Latn", None), ("por_Latn", "glg_Latn", None), ("spa_Latn", "glg_Latn", None),
    ("spa_Latn", "por_Latn", None), ("dan_Latn", "nob_Latn", None), ("nld_Latn", "dan_Latn", None),
    ("bul_Cyrl", "mkd_Cyrl", None), ("rus_Cyrl", "ukr_Cyrl", None), ("rus_Cyrl", "bul_Cyrl", None),
    ("srp_Cyrl", "mkd_Cyrl", None),
]
ROMAN_PAIRS = [("rus_Cyrl", "ukr_Cyrl"), ("rus_Cyrl", "bul_Cyrl"), ("bul_Cyrl", "mkd_Cyrl"),
               ("srp_Cyrl", "mkd_Cyrl"), ("rus_Cyrl", "srp_Cyrl")]
LANG2 = {"rus_Cyrl": "ru", "ukr_Cyrl": "uk", "bul_Cyrl": "bg", "mkd_Cyrl": "mk", "srp_Cyrl": "sr"}


def discriminators(a, b, wa, wb, tag, top=1500, n=150):
    """Words in A's top-`top` that do not occur in B's full list (and vice versa)."""
    sb, sa = set(wb), set(wa)
    a_only = [w for w in wa[:top] if w not in sb and len(w) > 1][:n]
    b_only = [w for w in wb[:top] if w not in sa and len(w) > 1][:n]
    shared = [w for w in wa[:200] if w in set(wb[:200])]
    d = os.path.join(CHALIS_DIR, "discriminators")
    os.makedirs(d, exist_ok=True)
    name = f"{a.split('_')[0]}-{b.split('_')[0]}{tag}.tsv"
    with open(os.path.join(d, name), "w", encoding="utf-8") as f:
        f.write(f"marker_for\tword\trank_in_own_list\n")
        for w in a_only:
            f.write(f"{a}\t{w}\t{wa.index(w) + 1}\n")
        for w in b_only:
            f.write(f"{b}\t{w}\t{wb.index(w) + 1}\n")
    return name, a_only[:25], b_only[:25], shared[:40]


def main():
    for code, name, fn, desc in VARIANTS:
        write_variant(code, name, fn, desc)

    summary = ["# CHALIS cousin-pair discriminators", "",
               "Each TSV lists frequent words (top 1500 of one language's 10k list) that do **not** "
               "occur anywhere in the other language's 10k list. These are high-precision cues for "
               "telling cousin languages apart. `*_nodiac` compares diacritic-stripped forms; "
               "`*_roman` compares English-style romanizations of Cyrillic languages.", "",
               "Caveat: vocabularies come from different corpora (wordfreq vs. OpenSubtitles for gl/sr), "
               "so a few 'markers' reflect corpus differences rather than the language.", ""]
    jobs = []
    for a, b, fn in PAIRS:
        wa, wb = vocab(a), vocab(b)
        tag = ""
        if fn:
            wa, wb, tag = [fn(w) for w in wa], [fn(w) for w in wb], "_nodiac"
            wa, wb = list(dict.fromkeys(wa)), list(dict.fromkeys(wb))
        jobs.append((a, b, wa, wb, tag))
    for a, b in ROMAN_PAIRS:
        wa = list(dict.fromkeys(cyr2lat_en(w, LANG2[a]) for w in vocab(a)))
        wb = list(dict.fromkeys(cyr2lat_en(w, LANG2[b]) for w in vocab(b)))
        jobs.append((a, b, wa, wb, "_roman"))
    for a, b, wa, wb, tag in jobs:
        name, ao, bo, sh = discriminators(a, b, wa, wb, tag)
        summary += [f"## {a} vs {b}{(' (' + tag.strip('_') + ')') if tag else ''}  -> `discriminators/{name}`", "",
                    f"- **{a} markers:** {', '.join(ao)}",
                    f"- **{b} markers:** {', '.join(bo)}",
                    f"- **Shared top-200 words (not diagnostic):** {', '.join(sh)}", ""]
        print(name)
    with open(os.path.join(CHALIS_DIR, "discriminators.md"), "w", encoding="utf-8") as f:
        f.write("\n".join(summary) + "\n")


if __name__ == "__main__":
    main()
